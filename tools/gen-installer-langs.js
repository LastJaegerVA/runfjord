// Generates installer/langs.nsh — the Windows installer's languages and texts,
// taken from the app's own translations so the two never drift apart.
//   node tools/gen-installer-langs.js
const fs = require('fs');
const path = require('path');
const I = require('../renderer/i18n.js');

// app language code -> NSIS language name (Bengali has no NSIS language file, so it falls back to English)
const NSIS = {
  en: 'English', ar: 'Arabic', bg: 'Bulgarian', cs: 'Czech', da: 'Danish', de: 'German', el: 'Greek', es: 'Spanish',
  fa: 'Farsi', fi: 'Finnish', fr: 'French', he: 'Hebrew', hi: 'Hindi', hr: 'Croatian', hu: 'Hungarian', id: 'Indonesian',
  it: 'Italian', ja: 'Japanese', ko: 'Korean', ms: 'Malay', nb: 'Norwegian', nl: 'Dutch', pl: 'Polish', pt: 'PortugueseBR',
  ro: 'Romanian', ru: 'Russian', sv: 'Swedish', sw: 'Swahili', th: 'Thai', tr: 'Turkish', uk: 'Ukrainian', vi: 'Vietnamese',
  'zh-CN': 'SimpChinese', 'zh-TW': 'TradChinese',
};
// "Desktop shortcut" — the one installer-only text
const DESKTOP = {
  en: 'Desktop shortcut', ar: 'اختصار على سطح المكتب', bg: 'Пряк път на работния плот', cs: 'Zástupce na ploše', da: 'Genvej på skrivebordet',
  de: 'Desktop-Verknüpfung', el: 'Συντόμευση στην επιφάνεια εργασίας', es: 'Acceso directo en el escritorio', fa: 'میانبر روی میزکار',
  fi: 'Pikakuvake työpöydälle', fr: 'Raccourci sur le bureau', he: 'קיצור דרך בשולחן העבודה', hi: 'डेस्कटॉप शॉर्टकट', hr: 'Prečac na radnoj površini',
  hu: 'Asztali parancsikon', id: 'Pintasan desktop', it: 'Collegamento sul desktop', ja: 'デスクトップのショートカット', ko: '바탕 화면 바로 가기',
  ms: 'Pintasan desktop', nb: 'Snarvei på skrivebordet', nl: 'Snelkoppeling op bureaublad', pl: 'Skrót na pulpicie', pt: 'Atalho na área de trabalho',
  ro: 'Comandă rapidă pe desktop', ru: 'Ярлык на рабочем столе', sv: 'Genväg på skrivbordet', sw: 'Njia ya mkato kwenye eneo-kazi',
  th: 'ทางลัดบนเดสก์ท็อป', tr: 'Masaüstü kısayolu', uk: 'Ярлик на робочому столі', vi: 'Lối tắt trên màn hình nền', 'zh-CN': '桌面快捷方式', 'zh-TW': '桌面捷徑',
};

const esc = (s) => String(s).replace(/\$/g, '$$$$').replace(/"/g, '$\\"').replace(/<[^>]+>/g, '');
let out = '; Generated by tools/gen-installer-langs.js — do not edit by hand\n\n';
// English first: it is the fallback for every language Windows has that we don't
const codes = ['en', ...Object.keys(NSIS).filter((c) => c !== 'en')];
// Not every NSIS release ships every language (e.g. NSIS 3.13 has no Swahili), so each one
// is only added when its language file exists — a missing one is skipped, not a build error.
const has = (c) => `!if /FileExists "\${NSISDIR}\\Contrib\\Language files\\${NSIS[c]}.nlf"\n`;
for (const c of codes) out += c === 'en' ? `!insertmacro MUI_LANGUAGE "English"\n` : `${has(c)}!insertmacro MUI_LANGUAGE "${NSIS[c]}"\n!else\n!warning "NSIS has no ${NSIS[c]} language file; skipping it"\n!endif\n`;
out += '\n';
for (const c of codes) {
  if (c !== 'en') out += has(c);
  I.setLang(c);
  const L = `\${LANG_${NSIS[c].toUpperCase()}}`;
  out += `LangString WelcomeTitle ${L} "${esc(I.t('welcome'))} \${VERSION}"\n`;
  out += `LangString WelcomeText ${L} "${esc(I.t('welcome_text'))}$\\r$\\n$\\r$\\n$(^ClickNext)"\n`;
  out += `LangString SecDeskName ${L} "${esc(DESKTOP[c])}"\n`;
  if (c !== 'en') out += '!endif\n';
}
fs.writeFileSync(path.join(__dirname, '..', 'installer', 'langs.nsh'), '\ufeff' + out); // BOM: NSIS on Windows needs it to read UTF-8
console.log(`installer/langs.nsh: ${codes.length} languages`);
